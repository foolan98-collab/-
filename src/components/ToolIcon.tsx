interface ToolIconProps extends LucideProps {
  name?: string;
  iconName?: string;
}

export const ToolIcon: React.FC<ToolIconProps> = ({ name, iconName, ...props }) => {
  const resolvedName = name || iconName || '';
  const IconComponent = ICON_MAP[resolvedName] || Wrench;
  return <IconComponent {...props} />;
};
