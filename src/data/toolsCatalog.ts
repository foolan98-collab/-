// Sorted by usefulness (priorityOrder) so دمج PDF, ضغط PDF, تقسيم PDF, تحويل الصور إلى PDF, تحويل PDF إلى Word appear first
export const SORTED_TOOLS_CATALOG: ToolItem[] = [...TOOLS_CATALOG].sort(
  (a, b) => (a.priorityOrder ?? a.id) - (b.priorityOrder ?? b.id)
);

export const POPULAR_TOOLS = SORTED_TOOLS_CATALOG.filter((tool) => tool.popular);

export function getToolBySlug(slug: string): ToolItem | undefined {
  return TOOLS_CATALOG.find((t) => t.slug === slug);
}

export function getToolsByCategory(categoryId: CategoryId): ToolItem[] {
  return SORTED_TOOLS_CATALOG.filter((t) => t.category === categoryId);
}

export function getToolsByFilterCategory(filterId: FilterCategoryId): ToolItem[] {
  if (filterId === 'all') return SORTED_TOOLS_CATALOG;
  if (filterId === 'documents') {
    return SORTED_TOOLS_CATALOG.filter((t) => t.isDocumentConversion);
  }
  return SORTED_TOOLS_CATALOG.filter((t) => t.category === filterId);
}
